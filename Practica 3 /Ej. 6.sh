6. El comando expr permite la evaluación de expresiones. Su sintaxis es:
  expr arg1 op arg2,
donde arg1 y arg2 representan argumentos y op la operación de la expresión.
Investigar que tipo de operaciones se pueden utilizar.
  El comando expr: (abreviatura de expresion) sirve para evaluar expresiones y mostrar su resultado por pantalla. Se usa principalmente en scripts antiguos o cuando 
  no se dispone de la expansiom aritmetica $(()).
  El tipo de operaciones que se pueden utilizar son:
  - Operaciones aritmeticas: +, -, *, / (division entera), % (modulo).
  - Operaciones relacionales o de comparacion: =, != (desigualdad de cadenas) , >, <, >=, <=. --> Evaluan cadenas.
  - Operaciones logicas: | (or) , & (and).
